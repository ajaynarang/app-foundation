#!/usr/bin/env node
/**
 * The convention gate: text-level rules that no spec or lint rule holds yet, checked in an instant. One
 * implementation, used by the Claude Code PostToolUse hook (.claude/hooks/convention-gate.mjs, advisory), the
 * pre-commit hook (lint-staged runs it on the staged files), the pre-push hook and `pnpm verify` (`pnpm guards`),
 * and the manual guards.yml workflow.
 *
 * Rules (ids are what a skill cites as `gate:<id>`):
 *   http-plain-error  `throw new Error(` in a controller or service on an HTTP path (not a processor, worker, step
 *                     or consumer): the client must get the error envelope, so throw a NestJS exception
 *   empty-catch       an empty catch block, or `.catch(() => {})`
 *   process-env       `process.env` outside config and bootstrap files
 *   raw-control       a raw `<button>` or `<input>` in the web app
 *   file-size         a backend or package source file over 800 lines; a web `.tsx` over 300
 *
 * Not here, because a spec holds them: console.* (log-hygiene.spec.ts), enum-shaped String columns
 * (schema-enum-conventions.spec.ts), status casing (status-call-sites.spec.ts, web-status-casing.spec.ts), palette
 * classes and date formatters (ui-grammar-guard.test.ts and the lint rule).
 *
 * The baseline (tools/guards/convention-gate.baseline.json) holds today's hits, one entry per file and rule with a
 * count. A count may only fall; a new file or rule fails. A count that fell fails too until the baseline is
 * rewritten, so the ratchet tightens. On a merge conflict, do not merge the file by hand: run --update-baseline,
 * which reads both sides of the conflict and allows the larger count of each entry.
 *
 * Moving a baselined hit (renaming a file, or splitting one as the file-size rule asks) makes a new key, which a
 * plain --update-baseline refuses. Add --allow-moved: it accepts new and raised keys as long as no rule's total
 * across the tree rises above the baseline's total, so hits moved and none were added. Use it only for a move, and
 * say so in the pull request; the baseline diff shows the old key gone and the new one in its place.
 *
 *   node tools/guards/convention-gate.mjs                     the whole tree against the baseline
 *   node tools/guards/convention-gate.mjs --files <f>...      only these files (pre-commit, through lint-staged)
 *   node tools/guards/convention-gate.mjs --update-baseline   rewrite the baseline; refuses a higher count or new key
 *     [--allow-moved]                                         accept moved hits: no rule's tree total may rise
 *   [--root <dir>]                                            another checkout (default: this file's repository)
 *
 * Node built-ins only; no git needed. Exit 1 on any finding.
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { isEntryModule, repoRootOf } from './workflow-config.mjs';

export const BASELINE_FILE = 'tools/guards/convention-gate.baseline.json';
const BASELINE_COMMENT =
  'Generated by `node tools/guards/convention-gate.mjs --update-baseline`; never edit or merge it by hand. Each entry is a file, a rule and the count of hits it may still have. A count may only fall; a new entry fails the gate.';

const SIZE_LIMIT = { source: 800, webTsx: 300 };

const SKIP_DIRS = new Set(['node_modules', '.git', '.turbo', '.next', 'dist', 'build', 'coverage', '.dart_tool']);
const SKIP_REL = ['.worktrees', '.claude/worktrees', 'tools/guards/fixtures', 'apps/mobile'];
const EXCLUDE = [
  /\.d\.ts$/,
  /\.(spec|test)\.tsx?$/,
  /(^|\/)(__tests__|__fixtures__|__mocks__|test|tests|e2e)\//,
  /(^|\/)generated\//,
  /\/prisma\/migrations\//,
];
const ENV_ALLOWED = [
  /(^|\/)config\//,
  /\.config\.[cm]?[jt]s$/,
  /(^|\/)main\.ts$/,
  /(^|\/)bootstrap\//,
  /(^|\/)instrument(ation)?(-[a-z]+)?\.ts$/,
  /\/telemetry\//,
  /(^|\/)scripts\//,
  /\/prisma\/seeds\//,
];
const HTTP_FILE = /^(apps\/backend\/src|packages\/appshore\/[^/]+\/src)\/.*\.(controller|service)\.ts$/;
const NOT_HTTP = /processor|worker|\.step\.|consumer/i;

/** The rules in the order they are reported. `applies` gets the repo-relative path; `count` the file text. */
export const RULES = [
  {
    id: 'http-plain-error',
    applies: (rel) => HTTP_FILE.test(rel) && !NOT_HTTP.test(path.posix.basename(rel)),
    count: (text) => matches(stripComments(text), /throw new Error\(/g),
    message:
      '`throw new Error(` on an HTTP path: throw a NestJS exception or an api-errors factory, so the client gets the error envelope',
  },
  {
    id: 'empty-catch',
    applies: () => true,
    count: (text) => {
      const code = stripComments(text, '/*c*/');
      return (
        matches(code, /\bcatch\s*(?:\([^)]*\))?\s*\{\s*\}/g) +
        matches(code, /\.catch\(\s*(?:\(\s*[\w$]*\s*\)|[\w$]+)\s*=>\s*\{\s*\}\s*\)/g)
      );
    },
    message: 'an empty catch swallows the error: log it, rethrow it, or say in a comment why it is safe to ignore',
  },
  {
    id: 'process-env',
    applies: (rel) => !ENV_ALLOWED.some((re) => re.test(rel)),
    count: (text) => matches(stripComments(text), /\bprocess\.env\b/g),
    message: '`process.env` outside config and bootstrap files: read it in the config module and pass the value in',
  },
  {
    id: 'raw-control',
    applies: (rel) => /^apps\/web\/src\/.*\.tsx$/.test(rel),
    count: (text) => matches(stripComments(text), /<(?:button|input)(?=[\s/>])/g),
    message: 'a raw `<button>` or `<input>`: use the shadcn component from the one component set',
  },
  {
    id: 'file-size',
    applies: () => true,
    count: (text, rel) => {
      const n = text.replace(/\n$/, '').split('\n').length;
      const limit = /^apps\/web\/.*\.tsx$/.test(rel) ? SIZE_LIMIT.webTsx : SIZE_LIMIT.source;
      return n > limit ? n : 0;
    },
    message: `over the size limit (${SIZE_LIMIT.source} lines, ${SIZE_LIMIT.webTsx} for a web .tsx; the count is the line count): split along a responsibility seam`,
  },
];
export const RULE_IDS = RULES.map((r) => r.id);
const RULE_BY_ID = Object.fromEntries(RULES.map((r) => [r.id, r]));

const matches = (text, re) => (text.match(re) ?? []).length;
const toPosix = (p) => p.split(path.sep).join('/');

/**
 * Replaces `//` and `/* *\/` comments with `replacement`, keeping string contents and every newline, so prose in a
 * comment does not count. A heuristic: regex literals are not parsed.
 */
export function stripComments(src, replacement = '') {
  let out = '';
  let i = 0;
  while (i < src.length) {
    const c = src[i];
    const next = src[i + 1];
    if (c === '/' && next === '/') {
      while (i < src.length && src[i] !== '\n') i++;
      out += replacement;
    } else if (c === '/' && next === '*') {
      i += 2;
      while (i < src.length && !(src[i] === '*' && src[i + 1] === '/')) {
        if (src[i] === '\n') out += '\n';
        i++;
      }
      i += 2;
      out += replacement;
    } else if (c === "'" || c === '"' || c === '`') {
      const start = i++;
      while (i < src.length && src[i] !== c) {
        if (src[i] === '\\') i++;
        else if (c !== '`' && src[i] === '\n') break;
        i++;
      }
      out += src.slice(start, i + 1);
      i++;
    } else {
      out += c;
      i++;
    }
  }
  return out;
}

/** Whether the gate checks this repo-relative path at all. */
export function inScope(rel) {
  if (!/^(apps|packages)\//.test(rel) || !/\.(ts|tsx|mts|cts)$/.test(rel)) return false;
  if (SKIP_REL.some((p) => rel === p || rel.startsWith(p + '/'))) return false;
  if (rel.split('/').some((seg) => SKIP_DIRS.has(seg))) return false;
  return !EXCLUDE.some((re) => re.test(rel));
}

/** The hits in one file as { ruleId: count }, only rules with a count above zero. */
export function checkFile(rel, text) {
  const out = {};
  if (!inScope(rel)) return out;
  for (const rule of RULES) {
    if (!rule.applies(rel)) continue;
    const n = rule.count(text, rel);
    if (n > 0) out[rule.id] = n;
  }
  return out;
}

function* walk(root, dir = root) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const abs = path.join(dir, e.name);
    const rel = toPosix(path.relative(root, abs));
    if (SKIP_REL.some((p) => rel === p || rel.startsWith(p + '/'))) continue;
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name)) yield* walk(root, abs);
    } else if (e.isFile()) yield rel;
  }
}

/** Every hit under `root` (or in `files`, repo-relative) as { file: { ruleId: count } }. */
export function countTree(root, files) {
  const out = {};
  const list = files ?? [...walk(root, path.join(root, 'apps')), ...walk(root, path.join(root, 'packages'))];
  for (const rel of list) {
    if (!inScope(rel)) continue;
    let text;
    try {
      text = fs.readFileSync(path.join(root, rel), 'utf8');
    } catch {
      continue;
    }
    const hits = checkFile(rel, text);
    if (Object.keys(hits).length) out[rel] = hits;
  }
  return out;
}

/** Reads baseline text; with merge-conflict markers, each entry allows the larger count of the two sides. */
export function parseBaselineText(text) {
  if (!/^<<<<<<< /m.test(text)) return JSON.parse(text).entries ?? {};
  const ours = [];
  const theirs = [];
  let side = null;
  for (const line of text.split('\n')) {
    if (line.startsWith('<<<<<<< ')) side = 'ours';
    else if (line.startsWith('|||||||') && side) side = 'base';
    else if (line.startsWith('=======') && side) side = 'theirs';
    else if (line.startsWith('>>>>>>> ') && side) side = null;
    else if (side === 'ours') ours.push(line);
    else if (side === 'theirs') theirs.push(line);
    else if (side === null) {
      ours.push(line);
      theirs.push(line);
    }
  }
  const merged = {};
  for (const entries of [JSON.parse(ours.join('\n')).entries ?? {}, JSON.parse(theirs.join('\n')).entries ?? {}])
    for (const [file, rules] of Object.entries(entries))
      for (const [rule, n] of Object.entries(rules))
        (merged[file] ??= {})[rule] = Math.max(merged[file]?.[rule] ?? 0, n);
  return merged;
}

/** The baseline under `root` as { file: { ruleId: count } }; empty when the file does not exist. */
export function loadBaseline(root) {
  const file = path.join(root, BASELINE_FILE);
  if (!fs.existsSync(file)) return {};
  return parseBaselineText(fs.readFileSync(file, 'utf8'));
}

/**
 * Compares current hits with the baseline. `over`: a count above what the baseline allows (a new entry allows 0).
 * `stale`: a count below it. With `files`, only those files' entries are compared.
 */
export function compareToBaseline(current, baseline, files) {
  const over = [];
  const stale = [];
  const scope = files ? new Set(files) : null;
  const keys = new Set([...Object.keys(current), ...Object.keys(baseline)]);
  for (const file of [...keys].sort()) {
    if (scope && !scope.has(file)) continue;
    const now = current[file] ?? {};
    const allowed = baseline[file] ?? {};
    for (const rule of RULE_IDS) {
      const count = now[rule] ?? 0;
      const limit = allowed[rule] ?? 0;
      if (count > limit) over.push({ file, rule, count, allowed: limit });
      else if (count < limit) stale.push({ file, rule, count, allowed: limit });
    }
  }
  return { over, stale };
}

/**
 * The rules whose total across the tree is above the baseline's total for that rule, as { rule, count, allowed }.
 * Empty when every hit over the baseline is one that moved from another file (a rename or a split).
 */
export function rulesThatGrew(current, baseline) {
  const total = (entries, rule) => Object.values(entries).reduce((a, r) => a + (r[rule] ?? 0), 0);
  const grew = [];
  for (const rule of RULE_IDS) {
    const count = total(current, rule);
    const allowed = total(baseline, rule);
    if (count > allowed) grew.push({ rule, count, allowed });
  }
  return grew;
}

/** One file against the baseline, for the edit hook: its hits, and what is over or under the baseline. */
export function checkOne(root, rel) {
  if (!inScope(rel)) return { hits: {}, over: [], stale: [] };
  const current = countTree(root, [rel]);
  const { over, stale } = compareToBaseline(current, loadBaseline(root), [rel]);
  return { hits: current[rel] ?? {}, over, stale };
}

export const ruleMessage = (id) => RULE_BY_ID[id]?.message ?? id;

function sortEntries(entries) {
  const out = {};
  for (const file of Object.keys(entries).sort()) {
    out[file] = {};
    for (const rule of RULE_IDS) if (entries[file][rule]) out[file][rule] = entries[file][rule];
  }
  return out;
}

function main() {
  const argv = process.argv.slice(2);
  const opt = (name) => {
    const i = argv.indexOf(name);
    return i > -1 ? argv[i + 1] : undefined;
  };
  const root = opt('--root') ? path.resolve(opt('--root')) : repoRootOf(import.meta.url);
  const fail = (lines, summary) => {
    for (const l of lines) console.error(l);
    console.log(`convention-gate: FAIL (${summary})`);
    process.exit(1);
  };
  const describe = (o, why) =>
    `${o.file}: [${o.rule}] ${o.count} hit(s), baseline ${o.allowed}: ${why ?? ruleMessage(o.rule)}`;

  let baseline;
  try {
    baseline = loadBaseline(root);
  } catch (e) {
    fail([`${BASELINE_FILE}: cannot read it (${e.message}); run --update-baseline`], 'unreadable baseline');
  }

  if (argv.includes('--update-baseline')) {
    const current = countTree(root);
    const existed = fs.existsSync(path.join(root, BASELINE_FILE));
    const { over } = compareToBaseline(current, baseline);
    if (existed && over.length) {
      if (!argv.includes('--allow-moved'))
        fail(
          over.map((o) => describe(o)),
          `${over.length} count(s) above the baseline; fix the code, the baseline only falls (if these hits only moved from a renamed or split file, add --allow-moved)`,
        );
      const grew = rulesThatGrew(current, baseline);
      if (grew.length)
        fail(
          grew.map(
            (g) => `[${g.rule}] ${g.count} hit(s) across the tree, baseline ${g.allowed}: ${ruleMessage(g.rule)}`,
          ),
          `${grew.length} rule total(s) above the baseline; --allow-moved accepts only hits that moved, fix the new ones`,
        );
    }
    const entries = sortEntries(current);
    fs.mkdirSync(path.dirname(path.join(root, BASELINE_FILE)), { recursive: true });
    fs.writeFileSync(
      path.join(root, BASELINE_FILE),
      JSON.stringify({ $comment: BASELINE_COMMENT, entries }, null, 2) + '\n',
    );
    const n = Object.values(entries).reduce((a, r) => a + Object.keys(r).length, 0);
    console.log(`convention-gate: baseline written (${n} entries in ${Object.keys(entries).length} files)`);
    return;
  }

  let files;
  if (argv.includes('--files')) {
    files = argv
      .slice(argv.indexOf('--files') + 1)
      .filter((a) => !a.startsWith('--'))
      .map((f) => toPosix(path.relative(root, path.resolve(f))))
      .filter((rel) => !rel.startsWith('..') && inScope(rel));
  }
  const current = countTree(root, files);
  const { over, stale } = compareToBaseline(current, baseline, files);
  const problems = [
    ...over.map((o) => describe(o)),
    ...stale.map((s) =>
      describe(s, 'fewer hits than the baseline allows; run `node tools/guards/convention-gate.mjs --update-baseline`'),
    ),
  ];
  if (problems.length) fail(problems, `${over.length} over the baseline, ${stale.length} stale`);
  const known = Object.values(current).reduce((a, r) => a + Object.keys(r).length, 0);
  console.log(`convention-gate: PASS (${known} baselined entr${known === 1 ? 'y' : 'ies'})`);
}

if (isEntryModule(import.meta.url)) main();
