#!/usr/bin/env node
// Regenerates alerting/*.yaml and dashboards/*.json from catalog/.
//
//   node infra/observability/grafana-cloud/scripts/generate.mjs           write the files
//   node infra/observability/grafana-cloud/scripts/generate.mjs --check   exit 1 if any committed file is stale
//
// Plain Node 20, no installed package: `pnpm init-app` runs it on a fresh clone.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildContactPoints, buildPolicies, buildRuleFiles, buildTemplates } from '../catalog/build-alerting.mjs';
import { DASHBOARDS } from '../catalog/dashboards/index.mjs';
import { isMain } from './lib/is-main.mjs';
import { toYaml } from './lib/yaml-emit.mjs';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER = '# GENERATED by scripts/generate.mjs from catalog/. Do not edit by hand.\n';
/** The folders generate.mjs owns: every file in them is one it writes. */
const GENERATED_DIRS = [
  ['alerting/rules', '.yaml'],
  ['dashboards', '.json'],
];

const yaml = (doc) => HEADER + toYaml(doc);
const json = (doc) => `${JSON.stringify(doc, null, 2)}\n`;

/** Every generated file as [repo-relative-to-grafana-cloud path, content]. */
export function outputs() {
  const files = buildRuleFiles().map(({ area, doc }) => [`alerting/rules/${area}.yaml`, yaml(doc)]);
  files.push(['alerting/contact-points.yaml', yaml(buildContactPoints())]);
  files.push(['alerting/notification-policies.yaml', yaml(buildPolicies())]);
  files.push(['alerting/templates.yaml', yaml(buildTemplates())]);
  for (const dash of DASHBOARDS) files.push([`dashboards/${dash.uid}.json`, json(dash)]);
  return files;
}

/** Files under the generated folders that the catalog no longer produces (a removed area or board). */
function orphans(root, expected) {
  const found = [];
  for (const [dir, ext] of GENERATED_DIRS) {
    const abs = join(root, dir);
    if (!existsSync(abs)) continue;
    for (const f of readdirSync(abs)) {
      const rel = `${dir}/${f}`;
      if (f.endsWith(ext) && !expected.has(rel)) found.push(rel);
    }
  }
  return found;
}

/** Paths whose committed content differs from the catalog, is missing, or should no longer exist. */
export function staleFiles(root = ROOT) {
  const files = outputs();
  const stale = files
    .filter(([rel, content]) => {
      const path = join(root, rel);
      return !existsSync(path) || readFileSync(path, 'utf8') !== content;
    })
    .map(([rel]) => rel);
  return [...stale, ...orphans(root, new Set(files.map(([rel]) => rel)))];
}

export function writeAll(root = ROOT, log = console.log) {
  const files = outputs();
  for (const [rel, content] of files) {
    const path = join(root, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    log(`wrote ${relative(process.cwd(), path)}`);
  }
  for (const rel of orphans(root, new Set(files.map(([r]) => r)))) {
    rmSync(join(root, rel));
    log(`removed ${relative(process.cwd(), join(root, rel))}`);
  }
}

function main() {
  if (!process.argv.includes('--check')) {
    writeAll();
    return;
  }
  const stale = staleFiles();
  if (stale.length) {
    console.error(
      `Stale generated files (run node infra/observability/grafana-cloud/scripts/generate.mjs):\n  ${stale.join('\n  ')}`,
    );
    process.exit(1);
  }
  console.log('Generated files are up to date.');
}

if (isMain(import.meta.url)) main();
